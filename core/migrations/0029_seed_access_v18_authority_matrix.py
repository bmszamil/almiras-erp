def _apply_roles(Role, RolePermission, roles):
    for code, (name_en, name_ar, scope, kind, system_code, perms) in roles.items():
        role, _ = Role.objects.update_or_create(code=code, defaults=dict(
            name_en=name_en, name_ar=name_ar, scope=scope, kind=kind, system_code=system_code, is_seeded=True,
            is_active=True))
        RolePermission.objects.filter(role=role).exclude(codename__in=perms).delete()
        for codename in perms:
            RolePermission.objects.get_or_create(role=role, codename=codename)


def seed(apps, schema_editor):
    from core.access.seed import apply_system_users

    Role = apps.get_model("core", "Role")
    _apply_roles(Role, apps.get_model("core", "RolePermission"), ROLES_CHANGED)
    apply_system_users(apps.get_model(*settings.AUTH_USER_MODEL.split(".")), apps.get_model("core", "UserProfile"),
                       {"governance": GOVERNANCE_USER})
    ApprovalActivity = apps.get_model("core", "ApprovalActivity")
    for code, name_en, name_ar, permission, basis, pending in ACTIVITIES:
        ApprovalActivity.objects.update_or_create(code=code, defaults=dict(
            name_en=name_en, name_ar=name_ar, permission=permission, amount_basis=basis, is_pending=pending))
    Entity = apps.get_model("core", "Entity")
    EntityGovernance = apps.get_model("core", "EntityGovernance")
    auditor = Role.objects.get(code="internal_auditor")
    for entity in Entity.objects.all():
        if EntityGovernance.objects.filter(entity=entity).exists():
            continue
        top = "managing_partner" if entity.parent_id is None and entity.consolidation == "parent" else "ceo"
        role = Role.objects.get(code=top)
        gov = EntityGovernance.objects.create(entity=entity, top_authority_role=role, self_approval_enabled=True)
        gov.governance_report_recipients.set([auditor, role])


