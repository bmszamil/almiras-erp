def text(key, language="en", **values):
    """The text ``key`` in ``language`` (``"ar"`` or anything else for English), with ``{name}`` values filled in."""
    en, ar = TEXTS[key]
    chosen = ar if language == "ar" else en
    return chosen.format(**values) if values else chosen


def both(key, **values):
    """``(English, Arabic)`` of ``key``, for pages that show both (error pages)."""
    return text(key, "en", **values), text(key, "ar", **values)
